import type {
  PaperFamily,
  PaperMargins,
  PaperSheet,
  RulingKind,
} from '../../../../lib/paper';

/**
 * Что и в каких границах перемерить.
 */
export type SheetRemeasureOptions = {
  /**
   * Семья, в которой лежит лист: её вид разлиновки решает, какие линии искать.
   */
  family: PaperFamily;

  /**
   * Перемеряемый лист.
   */
  sheet: PaperSheet;

  /**
   * Вид разлиновки листа; перемер его не меняет. У чистого листа линии не
   * ищутся, а шаг, фаза и поля, заданные руками, остаются.
   */
  kind: RulingKind;

  /**
   * Границы листа — отступы от краёв кадра в пикселях фотографии.
   */
  bounds: PaperMargins;
};

/**
 * Ошибка перемера вместе с листом, на котором она случилась.
 */
export type SheetRemeasureFailure = {
  /**
   * Идентификатор листа, перемер которого не удался.
   */
  sheetId: string;

  /**
   * Сообщение об ошибке.
   */
  message: string;
};

/**
 * Перемер своего листа в границах, заданных руками.
 */
export type SheetRemeasure = {
  /**
   * Проверяет границы, измеряет фотографию внутри них и заменяет
   * характеристики листа.
   */
  remeasure: (options: SheetRemeasureOptions) => Promise<void>;

  /**
   * Идёт перемер.
   */
  isBusy: boolean;

  /**
   * Сообщение об ошибке перемера текущего листа. `null` — ошибки нет.
   */
  error: string | null;

  /**
   * Сколько перемеров применено: формы листа, начальные значения которых
   * берутся из его характеристик, пересоздаются по смене этого числа.
   */
  revision: number;
};
