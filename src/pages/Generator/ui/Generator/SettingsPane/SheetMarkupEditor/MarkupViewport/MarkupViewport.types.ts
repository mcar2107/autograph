import type { ReactNode } from 'react';

import type { SheetFrame } from '../../../../../lib/paper';

export type MarkupViewportProps = {
  /**
   * Кадр фотографии: её размер в пикселях.
   */
  frame: SheetFrame;

  /**
   * Адрес фотографии листа.
   */
  photoSrc: string;

  /**
   * Подпись фотографии для читалки.
   */
  photoLabel: string;

  /**
   * Разметка поверх фотографии в её пикселях: следует за приближением и
   * сдвигом вместе со снимком.
   */
  children: ReactNode;
};

/**
 * Указатель, которым сдвигают фотографию.
 */
export type PanPointer = {
  /**
   * Идентификатор указателя: второй палец на экране сдвиг не перехватывает.
   */
  id: number;

  /**
   * Горизонталь указателя на прошлом шаге, экранные пиксели.
   */
  x: number;

  /**
   * Вертикаль указателя на прошлом шаге, экранные пиксели.
   */
  y: number;
};
