/**
 * Положение фотографии в окне редактора: масштаб и сдвиг её левого верхнего
 * угла. Одна матрица на фотографию и разметку.
 */
export type MarkupView = {
  /**
   * Экранных пикселей на пиксель фотографии.
   */
  scale: number;

  /**
   * Сдвиг левого края фотографии от левого края окна, экранные пиксели.
   */
  x: number;

  /**
   * Сдвиг верхнего края фотографии от верхнего края окна, экранные пиксели.
   */
  y: number;
};

/**
 * Размер окна просмотра в экранных пикселях.
 */
export type MarkupViewportSize = {
  /**
   * Ширина окна.
   */
  width: number;

  /**
   * Высота окна.
   */
  height: number;
};

/**
 * Точка окна в экранных пикселях от его левого верхнего угла.
 */
export type MarkupViewPoint = {
  /**
   * Горизонталь.
   */
  x: number;

  /**
   * Вертикаль.
   */
  y: number;
};

/**
 * Прямоугольник элемента в экранных пикселях от левого верхнего угла окна
 * просмотра.
 */
export type MarkupViewBox = {
  /**
   * Левый край.
   */
  left: number;

  /**
   * Верхний край.
   */
  top: number;

  /**
   * Правый край.
   */
  right: number;

  /**
   * Нижний край.
   */
  bottom: number;
};
