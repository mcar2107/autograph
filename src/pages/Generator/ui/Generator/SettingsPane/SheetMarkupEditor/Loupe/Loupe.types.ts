import type { SheetFrame, SheetPoint } from '../../../../../lib/paper';

export type LoupeProps = {
  /**
   * Адрес фотографии листа.
   */
  src: string;

  /**
   * Кадр фотографии в её пикселях.
   */
  frame: SheetFrame;

  /**
   * Точка фотографии в центре лупы, px фотографии.
   */
  point: SheetPoint;

  /**
   * Указатель в окне браузера: лупа стоит рядом с ним, а не под ним.
   */
  anchor: SheetPoint;

  /**
   * Масштаб фотографии в окне редактора: экранных пикселей на пиксель
   * фотографии. Лупа увеличивает сверх него.
   */
  scale: number;

  /**
   * Отражена ли фотография в окне — зеркальная страница: лупа показывает
   * снимок таким, каким его видно под ручкой.
   */
  isMirrored: boolean;

  /**
   * Куда лупа кладётся порталом: в диалог редактора, чтобы стоять над ним.
   */
  container: Element;
};

/**
 * Где стоит лупа: левый верхний угол в пикселях окна браузера.
 */
export type LoupePlacement = {
  /**
   * Отступ слева, px окна.
   */
  left: number;

  /**
   * Отступ сверху, px окна.
   */
  top: number;
};

/**
 * Размер окна браузера, в котором лупа должна поместиться.
 */
export type LoupeBounds = {
  /**
   * Ширина окна, px.
   */
  width: number;

  /**
   * Высота окна, px.
   */
  height: number;
};
