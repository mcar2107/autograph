/**
 * Инструмент редактора разметки: правит одну часть разметки, остальные
 * рисуются рядом бледно.
 */
export type MarkupToolId = 'outline' | 'lines' | 'bend' | 'margins';

/**
 * Что каркас редактора отдаёт инструменту. Черновик и его правку инструмент
 * берёт из стора редактора (`model/useMarkupEditorStore`), а не из пропсов.
 */
export type MarkupToolProps = {
  /**
   * Слой ручек поверх фотографии: инструмент кладёт туда свои ручки
   * порталом, в пикселях фотографии. `null` — слой ещё не смонтирован.
   */
  handleLayer: SVGGElement | null;

  /**
   * Страница, разметка которой показана: 0 — сам лист, 1 — зеркальная
   * страница разворота.
   */
  pageIndex: number;

  /**
   * Включён ли пробный текст: подсветки инструмента поверх фотографии
   * приглушаются вместе со слоями разметки, иначе закрывали бы буквы.
   */
  isMuted: boolean;
};
