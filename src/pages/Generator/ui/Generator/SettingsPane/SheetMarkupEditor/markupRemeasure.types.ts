/**
 * Очередь разборов фотографии одного источника.
 */
export type MarkupRemeasureQueue = {
  /**
   * Заводит новый запрос и ставит ожидание сохранения; прежние запросы
   * становятся устаревшими. Возвращает номер запроса.
   */
  start: () => number;

  /**
   * Последний ли это запрос: ответ на устаревший не применяется.
   */
  isLatest: (request: number) => boolean;

  /**
   * Снимает ожидание сохранения, если запрос последний: пока идёт более новый,
   * сохранение по-прежнему ждёт.
   */
  finish: (request: number) => void;

  /**
   * Делает устаревшим запрос в полёте и снимает ожидание: последнее действие
   * пользователя обошлось без разбора.
   */
  cancel: () => void;
};
