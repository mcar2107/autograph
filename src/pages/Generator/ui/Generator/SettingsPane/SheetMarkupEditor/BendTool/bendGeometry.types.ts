import type { SheetPoint } from '../../../../../lib/paper';

/**
 * Линия, за которую возьмётся нажатие в инструменте «Изгиб».
 */
export type BendLineGrab = {
  /**
   * Точка на нарисованной линии в столбце указателя, px фотографии.
   */
  point: SheetPoint;

  /**
   * Номер линии разлиновки: координата вдоль линий — `firstLinePhase + index·step`.
   */
  index: number;

  /**
   * Шаг разлиновки у этой точки по высоте кадра, px фотографии: на листе с
   * перспективой он свой в каждом месте кадра.
   */
  localStep: number;
};
