import type { SheetPoint } from '../../../../../lib/paper';

/**
 * Линия разлиновки в оверлее: ломаная в пикселях фотографии.
 */
export type RulingLinePath = {
  /**
   * Номер линии: её координата вдоль линий — `firstLinePhase + index·step`.
   */
  index: number;

  /**
   * Точки линии слева направо.
   */
  points: SheetPoint[];
};

/**
 * Прямоугольник в пикселях фотографии.
 */
export type MarkupBox = {
  /**
   * Левый край.
   */
  left: number;

  /**
   * Верхний край.
   */
  top: number;

  /**
   * Правый край.
   */
  right: number;

  /**
   * Нижний край.
   */
  bottom: number;
};

/**
 * Границы области письма в оверлее: верхняя и нижняя — концы у краёв листа,
 * боковые и линия поля — концы за верхом и низом кадра.
 */
export type MarginGuides = {
  /**
   * Граница верхнего поля.
   */
  top: SheetPoint[];

  /**
   * Граница нижнего поля.
   */
  bottom: SheetPoint[];

  /**
   * Граница левого поля — отрезок через всю высоту кадра.
   */
  left: SheetPoint[];

  /**
   * Граница правого поля — отрезок через всю высоту кадра.
   */
  right: SheetPoint[];

  /**
   * Линия поля — отрезок через всю высоту кадра. `null` — линии нет.
   */
  marginLine: SheetPoint[] | null;
};

/**
 * Атрибуты линии SVG в пикселях фотографии.
 */
export type LineAttributes = {
  /**
   * Горизонталь начала.
   */
  x1: number;

  /**
   * Вертикаль начала.
   */
  y1: number;

  /**
   * Горизонталь конца.
   */
  x2: number;

  /**
   * Вертикаль конца.
   */
  y2: number;
};
