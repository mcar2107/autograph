import type { SheetPoint } from '../../../../../lib/paper';

/**
 * Чем ручку сдвинули: указателем — перетаскиванием, клавиатурой — стрелкой.
 * Сдвиг стрелкой — точная правка на пиксель, и магнит её не отменяет.
 */
export type MarkupMoveSource = 'pointer' | 'keyboard';

/**
 * Роль ручки — от неё зависит форма: `corner` — угол контура или области
 * текста, квадрат; `edgeMiddle` — середина края области текста, ромб;
 * `lineEnd` — конец закреплённой линии или линии поля, круг.
 */
export type MarkupHandleKind = 'corner' | 'edgeMiddle' | 'lineEnd';

export type MarkupHandleProps = {
  /**
   * Роль ручки: задаёт её форму.
   */
  kind: MarkupHandleKind;

  /**
   * Горизонталь ручки в пикселях фотографии.
   */
  x: number;

  /**
   * Вертикаль ручки в пикселях фотографии.
   */
  y: number;

  /**
   * Подпись ручки для читалки: что именно она двигает.
   */
  label: string;

  /**
   * Колбэк на нажатие, начинающее перетаскивание: точка под указателем в
   * пикселях фотографии. От неё мерится, куда указатель ушёл за
   * перетаскивание, — точка самой ручки для этого не годится: нажимают не в
   * её центр.
   */
  onMoveStart?: (point: SheetPoint) => void;

  /**
   * Колбэк на каждое движение перетаскивания: точка под указателем в пикселях
   * фотографии.
   */
  onMove?: (point: SheetPoint) => void;

  /**
   * Колбэк на завершённый сдвиг: последняя точка перетаскивания или точка
   * после стрелки, и чем ручку сдвинули.
   */
  onMoveEnd?: (point: SheetPoint, source: MarkupMoveSource) => void;

  /**
   * Колбэк на оборванный системой жест (`pointercancel`): показанное
   * перетаскиванием в черновике ручка снимает сама, а инструмент — своё.
   */
  onMoveCancel?: () => void;

  /**
   * Ручка подсвечена ошибкой: то, что она ставит, не годится.
   */
  isFlagged?: boolean;

  /**
   * Дополнительные классы группы ручки.
   */
  className?: string;
};
