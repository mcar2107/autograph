/**
 * Что нужно пробному тексту от редактора.
 */
export type TrialTextInput = {
  /**
   * Пробный текст включён пользователем.
   */
  isEnabled: boolean;

  /**
   * Страница разворота: 0 — сам лист, 1 — зеркальная.
   */
  pageIndex: number;

  /**
   * Масштаб фотографии в окне: экранных пикселей на пиксель фотографии.
   * Страница рисуется в масштабе экрана — крупнее её всё равно не увидят.
   */
  scale: number;
};

/**
 * Пробная страница для показа.
 */
export type TrialTextRaster = {
  /**
   * Адрес готовой страницы. `null` — показывать нечего: пробный текст
   * выключен или страница по текущей разметке ещё не готова.
   */
  url: string | null;

  /**
   * Страница по текущей разметке заказана и ещё не пришла.
   */
  isPending: boolean;
};

/**
 * Готовая страница вместе с правкой, по которой она нарисована.
 */
export type TrialRaster = {
  /**
   * Адрес страницы.
   */
  url: string;

  /**
   * Правка разметки, по которой страница нарисована.
   */
  revision: string;
};
