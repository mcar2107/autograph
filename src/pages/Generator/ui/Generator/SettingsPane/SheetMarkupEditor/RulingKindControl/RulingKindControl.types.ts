/**
 * Чем кончился поиск линий после смены вида с «Без разлиновки»:
 *
 * - `applied` — линии нашлись и легли в черновик вместе с видом;
 * - `notFound` — линий на снимке нет: вид сменился, строки остались
 *   закреплёнными;
 * - `failed` — фотография не прочиталась: вид сменился, разметка прежняя;
 * - `dropped` — результат устарел: вид, контур или лист сменились, пока шёл
 *   поиск.
 */
export type RulingLinesSearchStatus = 'applied' | 'notFound' | 'failed' | 'dropped';
