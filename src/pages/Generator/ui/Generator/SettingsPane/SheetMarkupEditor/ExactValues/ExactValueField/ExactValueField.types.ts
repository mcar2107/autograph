export type ExactValueFieldProps = {
  /**
   * Подпись поля: что за число и в чём оно.
   */
  label: string;

  /**
   * От чего отсчитано число — например «от левого края кадра». Уходит в
   * описание поля: у чисел разметки разная точка отсчёта, и без неё одно и то
   * же поле показывает то 102, то 2631.
   */
  reference: string;

  /**
   * Текущее значение, px фотографии. `null` — значения нет, поле пустое.
   */
  value: number | null;

  /**
   * Колбэк на набранное число: Enter или уход фокуса. Возвращает, почему
   * число не применено, — текст ошибки у поля; `null` — применено.
   */
  onValueCommit: (value: number) => string | null;
};
