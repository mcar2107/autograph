import type {
  LightingField,
  PaperSheet,
  PaperTexture,
  RulingKind,
  RulingPin,
  SheetRuling,
} from '../lib/paper/paper.types';

/**
 * Загруженный пользователем лист: экземпляр вместе с семьёй, в которую он
 * добавлен, и признаком того, что характеристики уже посчитаны.
 */
export type UserSheetRecord = {
  /**
   * Идентификатор семьи, в которую добавлен экземпляр.
   */
  familyId: string;

  /**
   * Экземпляр листа со всеми его характеристиками.
   */
  sheet: PaperSheet;

  /**
   * Вид разлиновки листа. Лежит у листа, а не выводится из семьи: чистый лист
   * живёт в семье клетки или линейки, и перемер по виду семьи искал бы на нём
   * линии и затёр бы заданный руками шаг. Обязательный: забытый перенос вида
   * при сборке листа ловит компилятор.
   */
  kind: RulingKind;

  /**
   * Разлиновка, найденная автоматом, — к ней возвращает «Сбросить к
   * найденному». Хранится в памяти рядом с экземпляром, а не только в базе:
   * перезапись листа без неё затёрла бы её ручной разлиновкой.
   */
  measuredRuling: SheetRuling;

  /**
   * Вид разлиновки, предложенный автоматом по снимку: к нему вместе с
   * разлиновкой возвращает «Сбросить к найденному».
   */
  measuredKind: RulingKind;

  /**
   * Булавки, через которые подогнана гребёнка, в пикселях фотографии.
   */
  pins: RulingPin[];

  /**
   * Характеристики уже посчитаны. `false` — лист ждёт анализа: так он
   * отличается от восстановленного из хранилища, по которому анализ повторно
   * не запускается.
   */
  isAnalyzed: boolean;
};

/**
 * Карта текстуры в записи своего листа: картинка файлом, а не data URL, —
 * в base64 она весила бы на треть больше. Размер и размах лежат рядом: из
 * самой картинки размах не восстановить.
 */
export type StoredSheetTexture = Omit<PaperTexture, 'src'> & {
  /**
   * Полутоновая картинка карты.
   */
  image: Blob;
};

/**
 * Запись своего листа в IndexedDB: исходный файл, производные и разметка
 * одной записью, ключ — `id`.
 */
export type StoredUserSheet = Pick<PaperSheet, 'id' | 'label' | 'width' | 'height'> & {
  /**
   * Идентификатор семьи, к которой приписан лист.
   */
  familyId: string;

  /**
   * Вид разлиновки листа. Лежит в записи, а не выводится из семьи: чистый лист
   * и лист, вид которого поправлен в редакторе, живут не в семье своего вида.
   */
  kind: RulingKind;

  /**
   * Разлиновка листа с ручными правками.
   */
  ruling: SheetRuling;

  /**
   * Разлиновка, найденная автоматом: к ней возвращает «Сбросить к найденному»
   * и после перезапуска.
   */
  measuredRuling: SheetRuling;

  /**
   * Вид разлиновки, предложенный автоматом по снимку. Запись без поля
   * читается с видом листа.
   */
  measuredKind: RulingKind;

  /**
   * Булавки, через которые подогнана гребёнка, в пикселях фотографии.
   */
  pins: RulingPin[];

  /**
   * Поле освещения. `null` — не извлекалось.
   */
  lighting: LightingField | null;

  /**
   * Исходный файл фотографии как есть, без перекодирования.
   */
  source: Blob;

  /**
   * Карта текстуры. `null` — не извлекалась.
   */
  texture: StoredSheetTexture | null;
};

/**
 * Разметка своего листа, которую сохраняет редактор: разлиновка с правками,
 * булавки и вид. Найденная автоматом разлиновка сюда не входит — сохранение
 * правки её не меняет.
 */
export type UserSheetMarkup = Pick<UserSheetRecord, 'kind' | 'pins'> & {
  /**
   * Разлиновка листа с ручными правками.
   */
  ruling: SheetRuling;
};
