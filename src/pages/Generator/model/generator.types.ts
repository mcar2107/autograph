import type { RealismLevelId } from '../config';
import type { GeometryCorrection } from '../lib/calibrate/calibrate.types';
import type { PaperFamily } from '../lib/paper/paper.types';
import type { DistortionFlags } from '../lib/randomize/randomize.types';

import type { UserSheetMarkup, UserSheetRecord } from './userSheetsStorage.types';

/**
 * Поправка геометрии в сторе: те же дельты, что понимает автокалибровка, но
 * все до одной заданы. Пропущенная дельта ничем не отличалась бы от нулевой,
 * зато усложняла бы слияние правок с прежней поправкой.
 */
export type GeneratorGeometryCorrection = Required<GeometryCorrection>;

/**
 * Выбор чернил. Вариант из палитры хранится идентификатором тона, а не цветом:
 * свотч подсвечивается по тону, а не сравнением строк цвета, и произвольный
 * цвет, совпавший с цветом тона, выбранным тоном не считается.
 */
export type GeneratorInk =
  | {
      /**
       * Тон из палитры реальных ручек.
       */
      kind: 'tone';

      /**
       * Идентификатор тона в палитре.
       */
      toneId: string;
    }
  | {
      /**
       * Произвольный цвет.
       */
      kind: 'custom';

      /**
       * Цвет в форме `#rrggbb`.
       */
      color: string;
    };

/**
 * Реализм почерка: ступень и значения, которые она задаёт. Ступень хранится
 * явно, а не выводится сравнением с таблицей ступеней: иначе ручной набор,
 * совпавший со ступенью, и правка таблицы меняли бы подпись у сохранённого.
 */
export type GeneratorRealism = {
  /**
   * Выбранная ступень. `custom` — значения правились по отдельности.
   */
  level: RealismLevelId | 'custom';

  /**
   * Включённые виды случайных искажений почерка.
   */
  flags: DistortionFlags;

  /**
   * Как часто слово попадает под побуквенные искажения: 1 — каждое подходящее.
   */
  wordFrequency: number;

  /**
   * Верхняя граница числа искажаемых букв в слове.
   */
  letterFrequency: number;

  /**
   * Вариативность контуров букв: каждый экземпляр буквы получает свой контур.
   * `false` — рисуются исходные контуры шрифта.
   */
  hasContourVariance: boolean;
};

/**
 * Масштаб области просмотра: `fit` — лист вписан целиком, число — доля
 * натурального размера кадра.
 */
export type GeneratorZoom = 'fit' | number;

/**
 * Документ — то, что пользователь настроил: сохраняется между сеансами и
 * попадает в историю правок.
 */
export type GeneratorDocument = {
  /**
   * Исходный текст. Переводы строк — границы абзацев.
   */
  text: string;

  /**
   * Выбранный встроенный шрифт.
   */
  fontFamily: string;

  /**
   * Выбор чернил.
   */
  ink: GeneratorInk;

  /**
   * Идентификатор выбранной семьи листов: по её разлиновке считается
   * геометрия и раскладка.
   */
  familyId: string;

  /**
   * Идентификатор выбранного экземпляра листа внутри семьи. Влияет только на
   * внешность страницы — раскладку менять не может.
   */
  sheetId: string;

  /**
   * Экземпляр листа задан пользователем вручную: `sheetId` перебивает
   * раздачу листов по страницам, которую делает рецепт прогона, и стоит на
   * всех страницах. `false` — лист страницы берётся из рецепта.
   */
  isSheetPinned: boolean;

  /**
   * Реализм почерка.
   */
  realism: GeneratorRealism;

  /**
   * Ручная поправка поверх вычисленной геометрии. Дельты, а не значения:
   * поправка переживает смену экземпляра и семьи, потому что применяется к
   * заново вычисленному.
   */
  geometryCorrection: GeneratorGeometryCorrection;

  /**
   * Запас снизу в долях шага разлиновки листа страницы: сколько шагов над
   * нижним полем листа остаётся незаполненным. Доли шага, а не пиксели — на
   * листах с разным шагом запас отнимает одно и то же число строк.
   */
  bottomMargin: number;

  /**
   * Режим композиции: снимок страницы вкладывается в сцену при сохранении.
   */
  isSceneEnabled: boolean;

  /**
   * Идентификатор встроенной сцены.
   */
  sceneId: string;

  /**
   * Поворот страницы внутри сцены в градусах.
   */
  sceneRotate: number;

  /**
   * Сдвиг страницы внутри сцены по горизонтали в пикселях.
   */
  sceneShiftX: number;

  /**
   * Сдвиг страницы внутри сцены по вертикали в пикселях.
   */
  sceneShiftY: number;

  /**
   * Добавка к ширине вложенной страницы в пикселях: больше нуля — крупнее.
   */
  sceneScale: number;

  /**
   * Степень затемнения вложенной страницы, от 0 до 1.
   */
  sceneDarken: number;

  /**
   * Тень под вложенной страницей.
   */
  hasSceneShadow: boolean;

  /**
   * Seed прогона: из него выводится весь рецепт — листы по страницам, цвет
   * чернил, seed почерка и оптика. Правка текста и реализма его не меняет,
   * иначе каждое нажатие клавиши перекрашивало бы чернила и меняло листы.
   */
  runSeed: number;
};

/**
 * Просмотр — как пользователь смотрит на документ. Не входит в историю правок:
 * отмена не должна листать страницы и менять масштаб.
 */
export type GeneratorView = {
  /**
   * Номер открытой страницы, считая с нуля.
   */
  pageIndex: number;

  /**
   * Режим разворота: рядом показываются две страницы.
   */
  isSpread: boolean;

  /**
   * Масштаб области просмотра.
   */
  zoom: GeneratorZoom;
};

/**
 * Ресурсы — то, что загружено, а не настроено: файлы и данные, которые
 * восстанавливаются своими путями, а не из сохранённого документа.
 */
export type GeneratorResources = {
  /**
   * Предустановленные семьи листов. Отдельно от пользовательских листов,
   * потому что приходят из артефакта сборки и целиком заменяются, когда он
   * загрузился.
   */
  presetFamilies: PaperFamily[];

  /**
   * Загруженные пользователем листы вместе с семьёй, в которую добавлены.
   * Переживают перезагрузку: список восстанавливается из локального
   * хранилища.
   */
  userSheets: UserSheetRecord[];

  /**
   * Свои листы, которые локальное хранилище не приняло: квота исчерпана или
   * хранение данных сайта запрещено. Такой лист живёт до конца сессии, а
   * пользователь должен узнать, что после перезагрузки его не будет. Лист
   * уходит из списка, когда его удалось записать или его удалили.
   */
  unsavedUserSheetIds: string[];

  /**
   * Свои листы, удалённые из списка, которые хранилище не удалило: база
   * открылась, но удаление в ней сорвалось. После перезагрузки такой лист
   * вернётся, и пользователь должен об этом узнать.
   */
  undeletedUserSheetIds: string[];

  /**
   * Свои листы прочитаны из локального хранилища. Чтение асинхронное, и до
   * его конца ссылки сессии на свои листы не проверяются: лист, которого ещё
   * нет в списке, не считается пропавшим.
   */
  hasRestoredUserSheets: boolean;

  /**
   * Семейство загруженного пользователем шрифта. `null` — свой шрифт не
   * загружен; пока не `null`, он важнее выбора из списка.
   */
  customFontFamily: string | null;

  /**
   * Загруженная пользователем сцена как data URL. `null` — используется
   * встроенная.
   */
  customSceneSrc: string | null;

  /**
   * Режим «убрать фон»: лист не рисуется, остаётся только текст.
   */
  isBackgroundHidden: boolean;
};

/**
 * Параметры генератора — единственный источник правды о том, как выглядит
 * страница. DOM их только отображает.
 */
export type GeneratorState = GeneratorDocument & GeneratorView & GeneratorResources;

/**
 * Стор генератора: параметры плюс методы их изменения. Методы — именно методы,
 * а не хендлеры: обработчики событий живут в компонентах и вызывают их.
 */
export type GeneratorStore = GeneratorState & {
  /**
   * Меняет исходный текст.
   */
  setText: (text: string) => void;

  /**
   * Выбирает встроенный шрифт.
   */
  setFontFamily: (fontFamily: string) => void;

  /**
   * Ставит или сбрасывает (`null`) загруженный пользователем шрифт.
   */
  setCustomFontFamily: (fontFamily: string | null) => void;

  /**
   * Меняет выбор чернил.
   */
  setInk: (ink: GeneratorInk) => void;

  /**
   * Меняет числовой параметр геометрии блока текста.
   */
  setGeometry: (patch: Partial<GeneratorGeometry>) => void;

  /**
   * Включает или выключает режим «убрать фон».
   */
  setBackgroundHidden: (isHidden: boolean) => void;

  /**
   * Переключает один вид искажений. Реализм становится ручным (`custom`).
   */
  toggleDistortion: (flag: keyof DistortionFlags) => void;

  /**
   * Включает или выключает вариативность контуров букв. Реализм становится
   * ручным (`custom`).
   */
  setContourVariance: (hasContourVariance: boolean) => void;

  /**
   * Меняет частоту побуквенной обработки слов. Реализм становится ручным
   * (`custom`).
   */
  setWordFrequency: (wordFrequency: number) => void;

  /**
   * Меняет ограничение на число искажаемых букв. Реализм становится ручным
   * (`custom`).
   */
  setLetterFrequency: (letterFrequency: number) => void;

  /**
   * Выбирает ступень реализма: её значения перезаписывают флаги, частоты и
   * вариативность контуров. Seed прогона не меняется.
   */
  selectRealismLevel: (levelId: RealismLevelId) => void;

  /**
   * Включает или выключает режим композиции со сценой.
   */
  setSceneEnabled: (isEnabled: boolean) => void;

  /**
   * Выбирает встроенную сцену и сбрасывает загруженную.
   */
  selectScene: (sceneId: string) => void;

  /**
   * Ставит или сбрасывает (`null`) загруженную сцену.
   */
  setCustomScene: (src: string | null) => void;

  /**
   * Меняет параметры вложения страницы в сцену.
   */
  setSceneParams: (patch: Partial<GeneratorSceneParams>) => void;

  /**
   * Включает или выключает режим разворота.
   */
  setIsSpread: (isSpread: boolean) => void;

  /**
   * Меняет масштаб области просмотра.
   */
  setZoom: (zoom: GeneratorZoom) => void;

  /**
   * Открывает страницу с указанным номером.
   */
  goToPage: (pageIndex: number) => void;

  /**
   * Приводит номер открытой страницы к допустимому диапазону после пересчёта
   * разбивки.
   */
  clampPageIndex: (pageCount: number) => void;

  /**
   * Заменяет предустановленные семьи загруженными из артефакта. Выбор
   * пользователя сохраняется, пока в новых семьях есть та же семья и тот же
   * экземпляр.
   */
  setPresetFamilies: (families: PaperFamily[]) => void;

  /**
   * Выбирает семью листов и первый её экземпляр. Поправку геометрии не
   * трогает: она задана дельтами и применяется к новому расчёту. Ручной выбор
   * экземпляра при этом снимается: прежний принадлежал другой семье.
   */
  selectFamily: (familyId: string) => void;

  /**
   * Выбирает экземпляр листа внутри текущей семьи вручную: выбранный лист
   * встаёт на все страницы прогона и перебивает раздачу рецепта.
   */
  selectSheet: (sheetId: string) => void;

  /**
   * Добавляет загруженный пользователем лист и сохраняет его локально. Лист
   * доступен сразу, запись идёт следом; её отказ попадает в
   * `unsavedUserSheetIds`. Первое сохранение за сессию просит браузер не
   * вытеснять данные сайта.
   */
  addUserSheet: (record: UserSheetRecord) => void;

  /**
   * Сохраняет разметку своего листа — действие «Сохранить» редактора:
   * разлиновку с правками, булавки и вид. Найденная автоматом разлиновка
   * остаётся прежней, если разметка не несёт перемера по новому контуру: с
   * ним лист получает и его свет, текстуру и разметку автомата. Лист, вид
   * которого сменился, переезжает в семью этого
   * вида, и выбор, стоявший на нём, едет вместе с ним. Отказ записи попадает в
   * `unsavedUserSheetIds`, лист в памяти правку получает в любом случае.
   */
  saveSheetMarkup: (sheetId: string, markup: UserSheetMarkup) => void;

  /**
   * Удаляет пользовательский лист из списка и из локального хранилища. Если
   * удалён выбранный — выбор переходит на первый оставшийся экземпляр семьи.
   * Из списка лист уходит в любом случае, а отказ хранилища попадает в
   * `undeletedUserSheetIds`.
   */
  removeUserSheet: (sheetId: string) => void;

  /**
   * Восстанавливает пользовательские листы из локального хранилища вместе с
   * посчитанными характеристиками. Исполняется, когда листы прочитаны и ссылки
   * сессии на них проверены.
   */
  restoreUserSheets: () => Promise<void>;

  /**
   * Меняет часть поправки геометрии, оставляя остальные дельты как есть.
   */
  setGeometryCorrection: (patch: Partial<GeneratorGeometryCorrection>) => void;

  /**
   * Сбрасывает поправку: геометрия возвращается к вычисленной из разлиновки.
   */
  resetGeometryCorrection: () => void;

  /**
   * Запускает новый прогон — действие «Перегенерировать»: рецепт формируется
   * заново, и меняются листы незакреплённой семьи и рисунок почерка. Других способов сменить seed прогона нет.
   */
  startNewRun: () => void;
};

/**
 * Параметры геометрии, которые задаются в сторе значением, а не дельтой
 * поправки.
 */
export type GeneratorGeometry = Pick<GeneratorState, 'bottomMargin'>;

/**
 * Параметры вложения страницы в сцену.
 */
export type GeneratorSceneParams = Pick<
  GeneratorState,
  | 'sceneRotate'
  | 'sceneShiftX'
  | 'sceneShiftY'
  | 'sceneScale'
  | 'sceneDarken'
  | 'hasSceneShadow'
>;
