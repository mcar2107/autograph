import type { LineBounds } from '../calibrate/calibrate.types';
import type { GlyphSource } from '../glyph/glyph.types';
import type { LightingField, RulingBend, RulingPerspective } from '../paper/paper.types';
import type { LineDistortion, WordDistortion } from '../randomize/randomize.types';

/**
 * Метрики шрифта, от которых зависит вертикаль строки, — в долях кегля.
 * Структурный тип, а не импорт: рендереру нужны только эти две доли, а
 * `FontMetrics` из `lib/measure` под него подходит целиком.
 */
export type RenderFontMetrics = {
  /**
   * Подъём строчного бокса над базовой линией в долях кегля. Именно бокса, а
   * не чернил: на этом расстоянии от верха строки лежит базовая линия.
   */
  fontAscent: number;

  /**
   * Естественная высота строчного бокса (`line-height: normal`) в долях
   * кегля.
   */
  lineHeight: number;
};

/**
 * Изображение фона глазами рендерера. Рендерер о нём ничего не знает и только
 * передаёт в контекст: приложение подставляет загруженную картинку, тест —
 * заглушку с размерами.
 */
export type RenderImage = CanvasImageSource;

/**
 * Изображение, которое годится и в `drawImage`, и в текстуру шейдера. Уже, чем
 * `RenderImage`: списки источников у канвы и у WebGL не совпадают, и общий тип
 * держит карту текстуры в их пересечении — без него слой пришлось бы
 * приводить к чужому типу.
 */
export type InkTextureImage = ImageBitmap | HTMLCanvasElement | OffscreenCanvas;

/**
 * Канва, на которую ложится отдельный слой чернил. В воркере элемента `canvas`
 * нет, поэтому тип допускает и `OffscreenCanvas`.
 */
export type InkLayerImage = HTMLCanvasElement | OffscreenCanvas;

/**
 * Чем модулируются чернила: внешность выбранного экземпляра листа.
 */
export type InkModulationSource = {
  /**
   * Поле освещения экземпляра. `null` или непригодное поле заменяется
   * синтетическим: ровный след по всему листу — главный признак отрисовки.
   */
  lighting: LightingField | null;

  /**
   * Карта текстуры листа. `null` — карты нет, чернила модулируются одним
   * освещением.
   */
  texture: InkTextureImage | null;

  /**
   * Seed прогона: из него выводится синтетическое освещение, поэтому прогон
   * освещён одинаково при каждой отрисовке.
   */
  seed: number;
};

/**
 * Контуры шрифта страницы вместе с признаком вариативности. `null` вместо
 * этого объекта означает, что контуров нет: шрифт не разобрался или он
 * пользовательский, и текст рисуется обычным `fillText`.
 */
export type PageGlyphs = {
  /**
   * Источник контуров шрифта страницы.
   */
  source: GlyphSource;

  /**
   * Деформировать ли контур каждого экземпляра буквы. `false` — рисуются
   * исходные контуры шрифта, деформация не вызывается вовсе.
   */
  hasVariance: boolean;
};

/**
 * Результат измерения текста. Собственный тип вместо `TextMetrics`: рендереру
 * нужна только ширина, а заглушке в тесте — не выдумывать остальные поля.
 */
export type TextMetricsLike = {
  /**
   * Ширина текста в пикселях.
   */
  width: number;
};

/**
 * Минимальный контекст рисования: только то, чем пользуется рендерер.
 * `CanvasRenderingContext2D` подходит под этот тип целиком, а тест
 * подставляет запись вызовов.
 */
export type RenderContext = {
  /**
   * Цвет заливки текста.
   */
  fillStyle: string | CanvasGradient | CanvasPattern;

  /**
   * Шрифт в форме css-свойства `font`.
   */
  font: string;

  /**
   * От какой точки глифа отсчитывается координата `y` в `fillText`.
   */
  textBaseline: CanvasTextBaseline;

  /**
   * Запоминает текущее состояние контекста.
   */
  save(): void;

  /**
   * Возвращает состояние, запомненное последним `save`.
   */
  restore(): void;

  /**
   * Умножает текущее преобразование на масштаб.
   */
  scale(x: number, y: number): void;

  /**
   * Сдвигает начало координат.
   */
  translate(x: number, y: number): void;

  /**
   * Поворачивает систему координат на угол в радианах.
   */
  rotate(angle: number): void;

  /**
   * Умножает текущее преобразование на произвольную матрицу.
   */
  transform(a: number, b: number, c: number, d: number, e: number, f: number): void;

  /**
   * Рисует изображение в прямоугольник заданного размера.
   */
  drawImage(
    image: RenderImage,
    dx: number,
    dy: number,
    dWidth: number,
    dHeight: number
  ): void;

  /**
   * Ширина текста текущим шрифтом.
   */
  measureText(text: string): TextMetricsLike;

  /**
   * Рисует текст от точки на базовой линии.
   */
  fillText(text: string, x: number, y: number): void;

  /**
   * Начинает новый путь.
   */
  beginPath(): void;

  /**
   * Переводит перо без рисования.
   */
  moveTo(x: number, y: number): void;

  /**
   * Добавляет к пути отрезок прямой.
   */
  lineTo(x: number, y: number): void;

  /**
   * Добавляет к пути квадратичную кривую.
   */
  quadraticCurveTo(cpx: number, cpy: number, x: number, y: number): void;

  /**
   * Добавляет к пути кубическую кривую.
   */
  bezierCurveTo(
    cp1x: number,
    cp1y: number,
    cp2x: number,
    cp2y: number,
    x: number,
    y: number
  ): void;

  /**
   * Замыкает текущий контур пути.
   */
  closePath(): void;

  /**
   * Заливает путь текущим цветом.
   */
  fill(): void;
};

/**
 * Слой чернил вместе с его контекстом: рисовать на нём и отдать результат
 * шейдеру — разные роли одной и той же канвы.
 */
export type InkLayer = {
  /**
   * Контекст рисования слоя. `null` — контекста не дали.
   */
  context: RenderContext | null;

  /**
   * Сама канва как источник изображения и как текстура шейдера.
   */
  image: InkLayerImage;
};

/**
 * Создаёт слой чернил нужного размера. `null` — отдельного слоя не будет, и
 * чернила рисуются прямо на страницу.
 */
export type CreateInkLayer = (width: number, height: number) => InkLayer | null;

/**
 * Слово страницы вместе с его искажениями. Буквы со своими стилями лежат
 * внутри искажения слова.
 */
export type RenderWord = {
  /**
   * Текст слова без пробелов по краям.
   */
  text: string;

  /**
   * Искажения слова: поворот, скос, сдвиг и стили отдельных букв.
   */
  distortion: WordDistortion;

  /**
   * Seed вариативности контуров этого слова: из него выводится seed каждой его
   * буквы. Считается по месту слова в прогоне, поэтому два вхождения одного
   * слова написаны по-разному, а повторная отрисовка — одинаково.
   */
  seed: number;
};

/**
 * Строка страницы вместе с её искажениями.
 */
export type RenderLine = {
  /**
   * Слова строки в порядке отрисовки. Пустой массив — пустая строка между
   * абзацами: она ничего не рисует, но занимает свою высоту.
   */
  words: RenderWord[];

  /**
   * Искажения строки целиком.
   */
  distortion: LineDistortion;
};

/**
 * Страница, готовая к отрисовке: раскладка уже посчитана, искажения уже
 * выведены из seed. Рендерер только рисует.
 */
export type RenderPage = {
  /**
   * Строки страницы сверху вниз.
   */
  lines: RenderLine[];
};

/**
 * Фон страницы — фотография листа. Страница равна кадру листа, поэтому
 * фотография ложится от левого верхнего угла страницы во весь её размер: ни
 * сдвига, ни подгонки под чужой размер у неё нет.
 */
export type RenderBackground = {
  /**
   * Изображение листа.
   */
  image: RenderImage;

  /**
   * Ширина страницы в её пикселях — ширина кадра листа.
   */
  width: number;

  /**
   * Высота страницы в её пикселях — высота кадра листа.
   */
  height: number;
};

/**
 * Геометрия блока текста в пикселях страницы — до применения масштаба
 * отрисовки. Те же величины, по которым посчитана раскладка: разойтись им
 * нельзя, иначе базовые линии слезут с разлиновки.
 */
export type RenderGeometry = {
  /**
   * Кегль шрифта в пикселях. Именно в пикселях: стор держит кегль в em, и
   * перевод — забота вызывающей стороны.
   */
  fontSizePx: number;

  /**
   * Добавка к естественной высоте строки в пикселях. Отрицательная сжимает
   * строки.
   */
  lineSpacing: number;

  /**
   * Отступ верха первой строки от верха листа.
   */
  topOffset: number;

  /**
   * Отступ блока текста от левого края листа.
   */
  leftPadding: number;

  /**
   * Ширина блока текста в пикселях: та же, по которой посчитан перенос по
   * словам. Задаёт правую границу и точку, вокруг которой качается строка.
   * Ноль и меньше — границы нет.
   */
  blockWidth: number;

  /**
   * Края каждой строки на листе с наклонными полями: строка начинается со
   * своего сдвига от `leftPadding` и не выходит за свою ширину. Не задано —
   * у всех строк `leftPadding` и `blockWidth`, и лента вызовов та же, что у
   * листа без наклона полей.
   */
  lineBounds?: LineBounds;

  /**
   * Поворот блока текста целиком в градусах вокруг левого верхнего угла
   * листа.
   */
  blockRotate: number;

  /**
   * Метрики шрифта в долях кегля. Приходят снаружи, потому что снимаются с
   * настоящего начертания: у рукописных шрифтов естественная высота строки
   * уходит далеко от усреднённой, и подставленная доля уводит двадцатую
   * строку с разлиновки на сотни пикселей.
   */
  fontMetrics: RenderFontMetrics;

  /**
   * Изгиб линий разлиновки страницы в пикселях страницы; на чётной странице —
   * уже отражённый. Выбирается с углом `blockRotate`: отдельного наклона в
   * геометрии нет, а блок наклонён ровно на наклон той же разлиновки.
   *
   * `null` — лист ровный: точки контуров не сдвигаются, и отрисовка совпадает
   * с отрисовкой без изгиба вызов в вызов.
   */
  bend: RulingBend | null;

  /**
   * Перспектива разлиновки страницы в пикселях страницы; на чётной странице —
   * уже отражённая. Берётся с углом `blockRotate`: вместе они переводят точку
   * ровной наклонной раскладки в высоту её линии на фотографии.
   *
   * `null` — линии идут через равный шаг. Вместе с `bend: null` это значит,
   * что точки не сдвигаются вовсе.
   */
  perspective: RulingPerspective | null;
};

/**
 * Края одной строки в системе блока: где она начинается и сколько занимает —
 * то, что `LineBounds` хранит для всех строк страницы.
 */
export type LineSpan = {
  /**
   * Сдвиг начала строки от левого края блока вдоль неё, px.
   */
  offset: number;

  /**
   * Ширина строки, px: слова дальше неё не рисуются.
   */
  width: number;
};

/**
 * Всё, что нужно, чтобы отрисовать страницу: что рисовать, чем и в каком
 * разрешении.
 */
export type PageRenderParams = {
  /**
   * Страница с раскладкой и искажениями.
   */
  page: RenderPage;

  /**
   * Фон листа. `null` — фон скрыт, рисуются только чернила.
   */
  background: RenderBackground | null;

  /**
   * Цвет чернил в форме css-цвета.
   */
  inkColor: string;

  /**
   * Внешность листа, которой подчиняются чернила: освещение и текстура.
   */
  ink: InkModulationSource;

  /**
   * Контуры шрифта страницы. `null` — контуров нет, текст рисуется шрифтом
   * как есть.
   */
  glyphs: PageGlyphs | null;

  /**
   * Семейство шрифта страницы в форме css-свойства `font-family`.
   */
  fontFamily: string;

  /**
   * Геометрия блока текста.
   */
  geometry: RenderGeometry;

  /**
   * Множитель разрешения: 1 — пиксели страницы один в один, больше —
   * отрисовка в повышенном разрешении. Меняет только разрешение, но не состав
   * и не взаимное расположение элементов.
   */
  scale: number;
};
