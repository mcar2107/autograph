import type { TextMeasurer } from '../measure/measure.types';

/**
 * Строка текста после переноса по ширине. Отрисовывается отдельным элементом:
 * иначе к ней не применить построчные искажения («съезд линий», сдвиг строки).
 */
export type Line = {
  /**
   * Текст строки. Пустая строка — пустой абзац, отбивка между абзацами.
   */
  text: string;

  /**
   * Номер абзаца исходного текста, из которого получена строка. Строки одного
   * абзаца идут подряд, в том числе через границу страниц.
   */
  paragraphIndex: number;
};

export type SplitParagraphsOptions = {
  /**
   * Ширина блока текста в пикселях, по которой считается перенос.
   */
  width: number;

  /**
   * Ширина каждой строки вызова по её номеру, считая с нуля, в пикселях: на
   * листе с наклонными полями строки разной длины. Строкам дальше массива —
   * последняя ширина. Не задано — у всех строк `width`.
   */
  lineWidths?: readonly number[];

  /**
   * Кегль страницы в пикселях: им ширина фрагмента, отданная измерителем в
   * долях кегля, переводится в пиксели.
   */
  fontSizePx: number;

  /**
   * Измеритель, у которого спрашиваются ширины кандидатов в строку.
   */
  measure: TextMeasurer;

  /**
   * Позиция в исходном тексте, с которой продолжать, — `end` прошлого вызова.
   * Не задана — с начала текста.
   */
  start?: number;

  /**
   * Сколько строк набрать самое большее. Не задано — до конца текста. Меньше
   * единицы — ни одной строки, и позиция не сдвигается: защищаться от этого
   * должна вызывающая сторона.
   */
  maxLines?: number;
};

export type SplitParagraphsResult = {
  /**
   * Набранные строки по порядку.
   */
  lines: Line[];

  /**
   * Позиция в исходном тексте, с которой продолжать разбивку. Больше длины
   * текста — текст разобран целиком.
   */
  end: number;
};
