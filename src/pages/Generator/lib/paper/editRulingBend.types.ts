import type { SheetFrame } from './paper.types';

/**
 * Радиусы затухания правки изгиба в пикселях кадра.
 */
export type RulingBendRadius = {
  /**
   * Радиус поперёк линий — по координате вдоль линий: линии дальше двух
   * радиусов от перетаскиваемой не сдвигаются.
   */
  radius: number;

  /**
   * Радиус вдоль линий по горизонтали кадра: узлы дальше двух радиусов от
   * точки не сдвигаются.
   */
  radiusX: number;
};

/**
 * Настройки перетаскивания точки линии.
 */
export type RulingBendEdit = RulingBendRadius & {
  /**
   * Сдвиг на всю высоту столбца: все линии в столбце точки уходят на тот же
   * сдвиг, затухание остаётся только вдоль линий. Так правится прогиб у
   * пружины и переплёта.
   */
  isWholeColumn: boolean;

  /**
   * Кадр фотографии: от него отсчитываются правое и нижнее поля, когда сетку
   * изгиба приходится заводить заново.
   */
  frame: SheetFrame;
};
