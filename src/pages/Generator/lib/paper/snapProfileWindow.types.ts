/**
 * Профиль магнита и окно поиска в нём. Отсчёты профиля идут поперёк искомой
 * линии, каждый — среднее по полосе вдоль неё.
 */
export type SnapProfileWindow = {
  /**
   * Первый отсчёт профиля поперёк линии, px изображения.
   */
  from: number;

  /**
   * Число отсчётов профиля.
   */
  count: number;

  /**
   * Первая строка или столбец полосы вдоль линии, по которой усредняется
   * отсчёт, px изображения.
   */
  alongFrom: number;

  /**
   * Последняя строка или столбец полосы вдоль линии, включительно, px
   * изображения.
   */
  alongTo: number;

  /**
   * Первый отсчёт окна поиска — номер в профиле, а не координата.
   */
  windowFrom: number;

  /**
   * Последний отсчёт окна поиска, включительно, — номер в профиле.
   */
  windowTo: number;
};

/**
 * Вершина окна поиска магнита.
 */
export type SnapPeak = {
  /**
   * Номер вершины в профиле.
   */
  bin: number;

  /**
   * Оценка вершины: глубина провала или избыток красноты.
   */
  score: number;
};
