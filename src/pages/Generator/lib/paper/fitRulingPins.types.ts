import type { SheetRuling } from './paper.types';

/**
 * Гребёнка в модели перспективы с началом в середине булавок. Линия `k` —
 * `Y − X·t = a_k·(1 + qₓ·X + q_y·Y)`, где `X, Y` — отступ точки от начала, а
 * `a_k = offset + k·step` — её высота над началом в столбце начала.
 */
export type PinComb = {
  /**
   * Тангенс наклона линии, проходящей через начало.
   */
  tangent: number;

  /**
   * Высота линии с номером `0` над началом в его столбце, px.
   */
  offset: number;

  /**
   * Шаг разлиновки в столбце начала, px.
   */
  step: number;

  /**
   * Схождение линий по ширине кадра, 1/px.
   */
  convergenceX: number;

  /**
   * Изменение шага по высоте кадра, 1/px.
   */
  convergenceY: number;
};

/**
 * Итог подгонки гребёнки по булавкам.
 *
 * - `fitted` — гребёнка найдена и годна;
 * - `degenerate` — расстановка гребёнку не определяет: булавок меньше двух,
 *   у булавки нет длины, число шагов между булавками не задано или линии идут
 *   в обратном номерам порядке;
 * - `beyondHorizon` — гребёнка найдена, но в кадре уходит за горизонт
 *   перспективы, где высота линии неограниченно растёт.
 */
export type RulingPinsFit =
  | {
      /**
       * Гребёнка найдена и годна.
       */
      status: 'fitted';

      /**
       * Разлиновка с подогнанными шагом, фазой, наклоном и перспективой.
       */
      ruling: SheetRuling;

      /**
       * Невязка каждой булавки в порядке входа: наибольшее расстояние по
       * высоте от её концов до её линии, px.
       */
      residuals: number[];
    }
  | {
      /**
       * Расстановка гребёнку не определяет.
       */
      status: 'degenerate';
    }
  | {
      /**
       * Гребёнка уходит за горизонт внутри кадра.
       */
      status: 'beyondHorizon';

      /**
       * Невязка каждой булавки у отвергнутой гребёнки, px.
       */
      residuals: number[];
    };
