/**
 * Край листа, у которого стоит вертикальная линия поля.
 */
export type MarginLineSide = 'left' | 'right';

/**
 * Вид разлиновки семьи листов.
 */
export type RulingKind = 'grid' | 'lined' | 'blank';

/**
 * Поля листа в пикселях кадра его фотографии.
 */
export type PaperMargins = {
  /**
   * Отступ от верха листа до области письма.
   */
  top: number;

  /**
   * Отступ от правого края.
   */
  right: number;

  /**
   * Отступ от низа.
   */
  bottom: number;

  /**
   * Отступ от левого края.
   */
  left: number;
};

/**
 * Изгиб горизонтальных линий: равномерная сетка вертикальных смещений поверх
 * прямой наклонной гребёнки разлиновки. Сетка несёт собственную меру в
 * пикселях кадра, поэтому выборке не нужны ни ширина кадра, ни шаг.
 *
 * Строки узлов лежат вдоль линий: их координата — высота у левого края кадра
 * той прямой наклонной линии, что проходит через точку.
 */
export type RulingBend = {
  /**
   * Горизонталь первого узла в пикселях кадра.
   */
  columnOrigin: number;

  /**
   * Расстояние между соседними узлами строки по горизонтали в пикселях кадра.
   */
  columnSpacing: number;

  /**
   * Число узлов в строке.
   */
  columnCount: number;

  /**
   * Координата вдоль линий первой строки узлов: высота у левого края кадра
   * прямой наклонной линии, на которой строка лежит.
   */
  rowOrigin: number;

  /**
   * Расстояние между строками узлов в пикселях кадра — шаг гребёнки при
   * измерении.
   */
  rowSpacing: number;

  /**
   * Число строк узлов.
   */
  rowCount: number;

  /**
   * Вертикальные смещения линий в узлах в пикселях кадра, кратные сотой.
   * Положительное — вниз. Плоский массив построчно: узел `i` строки `r` лежит
   * по индексу `r * columnCount + i`.
   */
  offsets: number[];
};

/**
 * Точка в пикселях кадра фотографии.
 */
export type SheetPoint = {
  /**
   * Отступ от левого края кадра.
   */
  x: number;

  /**
   * Отступ от верхнего края кадра.
   */
  y: number;
};

/**
 * Контур листа на фотографии: четыре угла, а не прямоугольник, потому что
 * лист снят под углом и в перспективе. Выпуклый четырёхугольник с почти
 * осевыми сторонами.
 */
export type SheetOutline = {
  /**
   * Левый верхний угол листа.
   */
  topLeft: SheetPoint;

  /**
   * Правый верхний угол листа.
   */
  topRight: SheetPoint;

  /**
   * Правый нижний угол листа.
   */
  bottomRight: SheetPoint;

  /**
   * Левый нижний угол листа.
   */
  bottomLeft: SheetPoint;
};

/**
 * Кадр фотографии листа в пикселях. Сборке и отражению разлиновки он нужен
 * целиком: от сторон кадра отсчитываются контур листа и поля.
 */
export type SheetFrame = {
  /**
   * Ширина кадра.
   */
  width: number;

  /**
   * Высота кадра.
   */
  height: number;
};

/**
 * Перспектива разлиновки — дробно-линейная координата вдоль линий
 * (`lib/paper/rulingPerspective.ts`). При нулевых коэффициентах схождения она
 * совпадает с координатой прямой наклонной гребёнки при любом начале, поэтому
 * шаг, фаза, поля и изгиб сохраняют смысл.
 */
export type RulingPerspective = {
  /**
   * Начало отсчёта по ширине — середина кадра при измерении, px.
   */
  originX: number;

  /**
   * Начало отсчёта по высоте — середина кадра при измерении, px. В этой точке
   * шаг разлиновки равен `step`.
   */
  originY: number;

  /**
   * Схождение линий по ширине кадра, 1/px.
   */
  convergenceX: number;

  /**
   * Изменение шага по высоте кадра, 1/px.
   */
  convergenceY: number;
};

/**
 * Вторые концы боковых полей и линии поля — их положение у низа кадра. Первые
 * концы — у верха кадра: это `margins.left`, `margins.right` и `marginLineX`
 * разлиновки. Между концами граница блока идёт прямой.
 *
 * Положение отсчитано в системе блока текста, повёрнутой на наклон
 * разлиновки, как и первые концы: `x` вдоль строки при высоте блока `0` у
 * верха и высоте кадра у низа. Поэтому равные концы — ровно та граница, что
 * у разлиновки без второго конца: перпендикуляр к строкам.
 *
 * Лист, снятый на столе, лежит в кадре трапецией, и поле вдоль его стороны
 * наклонено. Одно число давало бы вертикаль, и между краем листа и текстом
 * рос бы пустой клин.
 */
export type RulingSideSlant = {
  /**
   * Отступ левого поля от левого края кадра у низа кадра.
   */
  left: number;

  /**
   * Отступ правого поля от правого края кадра у низа кадра.
   */
  right: number;

  /**
   * Отступ линии поля от левого края кадра у низа кадра. `null` — линии поля
   * нет, синхронно с `marginLineX`.
   */
  marginLineX: number | null;
};

/**
 * Проекция разлиновки на кадр: наклон и перспектива — всё, от чего зависит
 * координата вдоль линий. Разлиновка листа подходит сама.
 */
export type RulingProjection = {
  /**
   * Угол наклона разлиновки в градусах, как в `SheetRuling.skewAngle`.
   */
  skewAngle: number;

  /**
   * Перспектива разлиновки. `null` — линии идут через равный шаг.
   */
  perspective: RulingPerspective | null;
};

/**
 * Разлиновка экземпляра листа. Все величины — в пикселях его собственной
 * фотографии: общей меры у экземпляров нет, фотография под чужой шаг не
 * масштабируется.
 */
export type SheetRuling = {
  /**
   * Шаг разлиновки: расстояние между соседними горизонтальными линиями. `0` —
   * шаг не найден, разлиновку задают руками.
   */
  step: number;

  /**
   * Высота одной из линий разлиновки у левого края кадра. Любая линия годится:
   * остальные отстоят от неё на целое число шагов.
   */
  firstLinePhase: number;

  /**
   * Угол наклона разлиновки в кадре в градусах. Положительный — линии идут
   * вниз слева направо. Фотография не выправляется: по этому углу
   * выкладывается текст.
   */
  skewAngle: number;

  /**
   * Поля листа у левого края кадра. Не бывают нулевыми, если шаг найден: ноль
   * от детектора означает, что сторона не нашлась, и заменяется фолбэком.
   */
  margins: PaperMargins;

  /**
   * Отступ вертикальной линии поля от левого края кадра. `null` — линии поля
   * на листе нет.
   */
  marginLineX: number | null;

  /**
   * Край, у которого стоит линия поля. `null` — синхронно с `marginLineX`.
   */
  marginLineSide: MarginLineSide | null;

  /**
   * Боковые поля и линия поля у низа кадра. `null` — они идут от верха до
   * низа без наклона к строкам: концы у низа те же, что у верха. Поле
   * обязательное, как `bend`: забытый перенос ловит компилятор.
   */
  sideSlant: RulingSideSlant | null;

  /**
   * Изгиб линий поверх прямой гребёнки. `null` — линии прямые. Без шага изгиба
   * нет: сетка относилась бы к несуществующей гребёнке.
   */
  bend: RulingBend | null;

  /**
   * Перспектива разлиновки. `null` — линии идут через равный шаг, координата
   * вдоль линий — `y − x·tgθ`.
   */
  perspective: RulingPerspective | null;

  /**
   * Контур листа в пикселях кадра. `null` — лист занимает весь кадр.
   */
  outline: SheetOutline | null;

  /**
   * Линия поля и боковые поля зеркальной страницы, заданные отдельно от
   * отражённых. `null` — зеркало берёт их отражением оригинала. Поле
   * обязательное, как `bend`: забытый перенос ловит компилятор.
   */
  mirrorOverride: RulingMirrorOverride | null;
};

/**
 * Закреплённая линия разлиновки: номер линии и два её конца на фотографии.
 * Концы ставит пользователь на настоящую линию снимка, гребёнка подгоняется
 * через них.
 */
export type RulingPin = {
  /**
   * Номер линии в гребёнке: её координата вдоль линий —
   * `firstLinePhase + index·step`. Число шагов между соседними булавками —
   * разность номеров; равные номера — число шагов не задано.
   */
  index: number;

  /**
   * Левый конец линии в пикселях кадра фотографии.
   */
  left: SheetPoint;

  /**
   * Правый конец линии в пикселях кадра фотографии.
   */
  right: SheetPoint;
};

/**
 * Линия поля и боковые поля зеркальной страницы в пикселях отражённого кадра.
 * Отражённая линия поля часто ложится не туда: у правой страницы разворота
 * своя черта, и пользователь задаёт её отдельно. Остальная разметка у
 * зеркала общая с оригиналом — у отражённого снимка те же линии.
 */
export type RulingMirrorOverride = {
  /**
   * Отступ линии поля от левого края отражённого кадра. `null` — линии поля у
   * зеркала нет.
   */
  marginLineX: number | null;

  /**
   * Край отражённого кадра, у которого стоит линия поля. `null` — синхронно с
   * `marginLineX`.
   */
  marginLineSide: MarginLineSide | null;

  /**
   * Левое поле зеркальной страницы.
   */
  marginLeft: number;

  /**
   * Правое поле зеркальной страницы.
   */
  marginRight: number;

  /**
   * Боковые поля и линия поля зеркальной страницы у низа отражённого кадра.
   * `null` — без наклона к строкам.
   */
  sideSlant: RulingSideSlant | null;
};

/**
 * Исходные данные разлиновки: результат детектора с наклоном или запись
 * прежней формы, в которой полей и линии поля нет вовсе.
 */
export type SheetRulingSource = {
  /**
   * Шаг разлиновки в пикселях фотографии. `0` — шаг не найден.
   */
  step: number;

  /**
   * Высота одной из линий у левого края кадра.
   */
  firstLinePhase: number;

  /**
   * Угол наклона разлиновки в градусах.
   */
  skewAngle: number;

  /**
   * Поля, как их нашёл детектор. Нулевое поле — сторона не найдена. Не задано —
   * не найдена ни одна сторона.
   */
  margins?: PaperMargins;

  /**
   * Отступ линии поля от левого края. `null` или не задано — линии нет.
   */
  marginLineX?: number | null;

  /**
   * Край, у которого стоит линия поля. `null` или не задано — линии нет.
   */
  marginLineSide?: MarginLineSide | null;

  /**
   * Боковые поля и линия поля у низа кадра. `null` или не задано — без
   * наклона к строкам.
   */
  sideSlant?: RulingSideSlant | null;

  /**
   * Изгиб линий. `null` или не задано — линии прямые. `null` допустим явно,
   * чтобы источник собирался спредом из детекции.
   */
  bend?: RulingBend | null;

  /**
   * Перспектива разлиновки. `null` или не задано — линии идут через равный
   * шаг.
   */
  perspective?: RulingPerspective | null;

  /**
   * Контур листа в пикселях кадра. `null` или не задано — лист во весь кадр.
   */
  outline?: SheetOutline | null;

  /**
   * Отдельно заданные линия поля и боковые поля зеркальной страницы. `null`
   * или не задано — зеркало берёт их отражением.
   */
  mirrorOverride?: RulingMirrorOverride | null;
};

/**
 * Низкочастотное поле освещения листа: сетка нормированных яркостей, снятая с
 * фотографии пустого листа.
 */
export type LightingField = {
  /**
   * Число столбцов сетки.
   */
  gridWidth: number;

  /**
   * Число строк сетки.
   */
  gridHeight: number;

  /**
   * Яркости узлов сетки от 0 до 1, построчно сверху вниз. Нормированы на
   * самый светлый узел: у него ровно 1, поэтому поле описывает форму света, а
   * не абсолютную экспозицию снимка.
   */
  values: number[];

  /**
   * Размах яркости по листу: разница между светлой и тёмной частью в долях
   * самой светлой части. По нему решается пригодность поля.
   */
  contrast: number;

  /**
   * Пригодность поля к использованию. `false` — источник освещён равномерно
   * (скан), отрисовка берёт синтетическое освещение.
   */
  isUsable: boolean;
};

/**
 * Размер сетки поля освещения.
 */
export type LightingGrid = {
  /**
   * Число столбцов сетки.
   */
  gridWidth: number;

  /**
   * Число строк сетки.
   */
  gridHeight: number;
};

/**
 * Настройки извлечения поля освещения.
 */
export type ExtractLightingOptions = {
  /**
   * Число клеток вдоль длинной стороны листа.
   */
  gridSize?: number;

  /**
   * Порог размаха яркости, начиная с которого поле пригодно.
   */
  usableContrast?: number;

  /**
   * Контур листа в пикселях кадра: клетка за ним берёт значение ближайшей
   * клетки с бумагой и не входит ни в нормировку, ни в размах. `null` или не
   * задано — лист занимает весь кадр.
   */
  outline?: SheetOutline | null;
};

/**
 * Настройки извлечения карты текстуры.
 */
export type ExtractTextureOptions = {
  /**
   * Во сколько раз прореживать карту относительно фотографии. Целое число от
   * единицы; дробная часть отбрасывается. Не задано — прореживание берётся
   * таким, чтобы длинная сторона карты уложилась в её предел.
   */
  downscale?: number;

  /**
   * Доля отклонений, укладывающихся в размах карты.
   */
  amplitudePercentile?: number;

  /**
   * Контур листа в пикселях кадра: блок с центром за ним получает нулевое
   * отклонение и не входит ни в подгонку уровня, ни в размах. `null` или не
   * задано — лист занимает весь кадр.
   */
  outline?: SheetOutline | null;
};

/**
 * Сырая карта высокочастотных отклонений: яркость пикселя минус
 * интерполированное поле освещения. Отделена от `PaperTexture`, потому что
 * считается чистой математикой без DOM, а кодирование в data URL требует
 * браузерного canvas.
 */
export type TextureMap = {
  /**
   * Ширина карты в пикселях.
   */
  width: number;

  /**
   * Высота карты в пикселях.
   */
  height: number;

  /**
   * Отклонения яркости, построчно сверху вниз. Ноль — пиксель ровно на поле
   * освещения, знак — темнее или светлее его.
   */
  values: Float32Array;

  /**
   * Размах отклонений в долях яркости, в который укладывается зерно бумаги.
   * Отклонения крупнее размаха есть всегда: разлиновка и соринки на порядок
   * темнее зерна, и если растянуть шкалу на них, само зерно ужмётся в
   * несколько уровней яркости карты.
   */
  amplitude: number;
};

/**
 * Высокочастотная карта текстуры бумаги: отклонения яркости от поля
 * освещения, свёрнутые в изображение для шейдера.
 */
export type PaperTexture = {
  /**
   * Карта отклонений как data URL полутонового изображения: 0 и 1 —
   * отклонение на `amplitude` в тёмную и светлую сторону, всё, что крупнее,
   * срезано границей. Нулевому отклонению отвечает 128/255, а не ровно 0.5:
   * середина восьмибитной шкалы не попадает на 0.5, и постоянное смещение в
   * полпроцента размаха неустранимо без второго канала.
   */
  src: string;

  /**
   * Ширина карты в пикселях.
   */
  width: number;

  /**
   * Высота карты в пикселях.
   */
  height: number;

  /**
   * Размах отклонений в долях яркости: множитель, которым шейдер разворачивает
   * значение пикселя карты обратно в отклонение яркости.
   */
  amplitude: number;
};

/**
 * Экземпляр листа: фотография и её измеренные характеристики, включая
 * разлиновку в пикселях этой фотографии.
 */
export type PaperSheet = {
  /**
   * Идентификатор экземпляра, уникальный внутри приложения.
   */
  id: string;

  /**
   * Подпись экземпляра в списке.
   */
  label: string;

  /**
   * Фотография листа: путь от корня сайта у предустановленных, data URL у
   * пользовательских.
   */
  src: string;

  /**
   * Ширина фотографии в пикселях.
   */
  width: number;

  /**
   * Высота фотографии в пикселях.
   */
  height: number;

  /**
   * Разлиновка экземпляра в пикселях его фотографии. Шаг, фаза, наклон и поля
   * лежат только здесь: у листа нет второго места, из которого их можно
   * прочитать и разойтись с разлиновкой.
   */
  ruling: SheetRuling;

  /**
   * Поле освещения. `null` — не извлекалось.
   */
  lighting: LightingField | null;

  /**
   * Карта текстуры бумаги. `null` — не извлекалась.
   */
  texture: PaperTexture | null;
};

/**
 * Семья листов: вид разлиновки и экземпляры-фотографии. Семья — группа, внутри
 * которой рецепт прогона раздаёт страницам фон; разлиновка у каждого экземпляра
 * своя.
 */
export type PaperFamily = {
  /**
   * Идентификатор семьи.
   */
  id: string;

  /**
   * Подпись семьи в списке.
   */
  label: string;

  /**
   * Вид разлиновки семьи: от него зависит, сколько шагов разлиновки занимает
   * строка на её пресетах.
   */
  kind: RulingKind;

  /**
   * Экземпляры семьи. Пустым не бывает: семья без фотографий нечем
   * отрисовывается.
   */
  sheets: PaperSheet[];

  /**
   * Вид разлиновки своих листов семьи по идентификатору листа. Число шагов на
   * строку берётся у листа, а не у семьи: чистый лист лежит в семье клетки
   * или линейки, но строка на нём — ровно заданный шаг. Нет записи — лист
   * пресетный, и вид у него семейный.
   */
  sheetKinds?: Record<string, RulingKind>;
};

/**
 * Полутоновая выжимка изображения листа — вход всех измерений. Отделена от
 * DOM: анализ тестируется на сгенерированных массивах без браузера.
 */
export type SheetImageData = {
  /**
   * Ширина в пикселях.
   */
  width: number;

  /**
   * Высота в пикселях.
   */
  height: number;

  /**
   * Яркости пикселей от 0 (чёрный) до 1 (белый), построчно сверху вниз.
   */
  luminance: Float32Array;

  /**
   * Разность красного и зелёного каналов пикселя в уровнях 8-битного канала,
   * от −255 до 255, построчно, как `luminance`. По ней красная черта поля
   * отличается от нейтральной вертикали той же темноты — витка спирали, линии
   * клетки, тени.
   *
   * Поле необязательное: изображение только с яркостью измеряется так же, как
   * серый снимок, без вето по цвету.
   */
  redMinusGreen?: Int16Array;
};

/**
 * Найденная на фотографии разлиновка вместе с признаком удачи: неудача не
 * отбрасывает фотографию, а включает ручной ввод.
 */
export type RulingDetection = {
  /**
   * Найден ли шаг разлиновки.
   */
  isDetected: boolean;

  /**
   * Измеренный шаг разлиновки в пикселях фотографии. `0` — не найден.
   */
  step: number;

  /**
   * Смещение первой линии от верха фотографии в пикселях фотографии.
   */
  firstLinePhase: number;

  /**
   * Найденный вид разлиновки: `grid` — есть и вертикальные линии с тем же
   * шагом, `lined` — только горизонтальные.
   */
  kind: RulingKind;

  /**
   * Поля, найденные по границам области с линиями, в пикселях фотографии.
   */
  margins: PaperMargins;

  /**
   * Отступ вертикальной линии поля от левого края в пикселях фотографии.
   * `null` — линия поля не найдена.
   */
  marginLineX: number | null;

  /**
   * Край, у которого стоит линия поля. `null` — линии поля нет, синхронно с
   * `marginLineX`. Сторона нужна, потому что лист может быть снят как правая
   * половина разворота: тогда поле справа, и зеркалирование чётных страниц
   * должно это учитывать.
   */
  marginLineSide: MarginLineSide | null;

  /**
   * Изгиб линий, измеренный по фотографии. `null` — линии прямые или изгиб не
   * удалось измерить надёжно.
   */
  bend: RulingBend | null;

  /**
   * Перспектива разлиновки, измеренная по фотографии. `null` — линии идут через
   * равный шаг или перспективу не удалось измерить надёжно.
   */
  perspective: RulingPerspective | null;

  /**
   * Уверенность в найденном шаге от 0 до 1: отношение пика автокорреляции к
   * фону профиля по всему кадру.
   *
   * Число для отчётов, а не признак удачи: `isDetected` она решает только за
   * первую ступень замера. Профиль по кадру не взял порог — шаг ищет
   * полосовая ступень, и у листа, которому она его нашла, разлиновка найдена
   * при уверенности ниже порога. Что сделала сама ступень, видно по
   * `bandedStage` детектора.
   */
  confidence: number;
};
