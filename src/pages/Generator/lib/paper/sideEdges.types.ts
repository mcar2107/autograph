/**
 * Граница блока текста сбоку: левое поле, правое поле или линия поля.
 */
export type SideEdge = 'left' | 'right' | 'marginLine';

/**
 * Концы боковой границы блока — положение вдоль строки от левого края кадра в
 * системе блока, повёрнутой на наклон разлиновки: у верха кадра (высота блока
 * `0`) и у низа (высота блока — высота кадра). Равные концы — перпендикуляр к
 * строкам.
 */
export type SideEdgeEnds = {
  /**
   * Конец у верха кадра, px.
   */
  top: number;

  /**
   * Конец у низа кадра, px.
   */
  bottom: number;
};

/**
 * Поворот на наклон разлиновки.
 */
export type SideEdgeRotation = {
  /**
   * Синус наклона.
   */
  sin: number;

  /**
   * Косинус наклона.
   */
  cos: number;
};

/**
 * Точка фотографии в системе блока.
 */
export type SideEdgeBlockPoint = {
  /**
   * Положение вдоль строки, px.
   */
  x: number;

  /**
   * Высота в системе блока, px.
   */
  v: number;
};
