import type { RulingKind, SheetRuling } from '../paper/paper.types';

/**
 * Лист страницы, по которому считается геометрия блока: разлиновка в пикселях
 * его фотографии и кадр. На зеркальной странице разлиновка приходит уже
 * отражённой — расчёт по чётности не ветвится.
 */
export type SheetCalibration = {
  /**
   * Разлиновка листа страницы в пикселях кадра.
   */
  ruling: SheetRuling;

  /**
   * Вид разлиновки листа: сколько шагов разлиновки занимает строка.
   */
  kind: RulingKind;

  /**
   * Ширина кадра листа в пикселях: правое поле отсчитывается от правого края.
   */
  width: number;

  /**
   * Высота кадра листа в пикселях: нижнее поле отсчитывается от нижнего края.
   */
  height: number;
};

/**
 * Геометрия блока текста в пикселях кадра листа страницы. Пиксели, а не em:
 * `em` — единица DOM, и появляется она только на границе со стилями.
 */
export type BlockGeometry = {
  /**
   * Кегль в пикселях.
   */
  fontSizePx: number;

  /**
   * Добавка к естественной высоте строки в пикселях. Отрицательная сжимает
   * строки: у рукописных шрифтов строчный бокс обычно выше шага разлиновки.
   */
  lineSpacing: number;

  /**
   * Отступ верха первой строки от верха листа в пикселях.
   */
  topOffset: number;

  /**
   * Отступ блока текста от левого края листа в пикселях.
   */
  leftPadding: number;

  /**
   * Ширина блока текста в пикселях: по ней считается перенос по словам.
   */
  blockWidth: number;
};

/**
 * Ручная поправка: дельты поверх вычисленной геометрии в долях шага
 * разлиновки листа страницы. Именно дельты, а не значения, — поправка
 * переживает смену экземпляра листа и смену семьи, потому что применяется к
 * заново вычисленному. Доли шага, а не пиксели: пиксель у каждой фотографии
 * свой, и одна пиксельная дельта на разных листах сдвигала бы текст на разную
 * долю строки.
 */
export type GeometryCorrection = {
  /**
   * Дельта кегля в долях шага разлиновки.
   */
  fontSizePx?: number;

  /**
   * Дельта межстрочного интервала в долях шага разлиновки.
   */
  lineSpacing?: number;

  /**
   * Дельта верхнего отступа в долях шага разлиновки.
   */
  topOffset?: number;

  /**
   * Дельта левого отступа в долях шага разлиновки.
   */
  leftPadding?: number;

  /**
   * Дельта ширины блока в долях шага разлиновки.
   */
  blockWidth?: number;
};

/**
 * То, из чего складывается геометрия блока: разлиновка листа страницы, сведённая
 * к шагу, первой линии и краям блока.
 */
export type GeometryBasis = {
  /**
   * Вид разлиновки листа.
   */
  kind: RulingKind;

  /**
   * Шаг разлиновки в пикселях, больше нуля.
   */
  step: number;

  /**
   * Высота линии, на которую садится базовая линия первой строки.
   */
  firstLine: number;

  /**
   * Левый край блока текста в пикселях.
   */
  left: number;

  /**
   * Правый край блока текста в пикселях.
   */
  right: number;
};
